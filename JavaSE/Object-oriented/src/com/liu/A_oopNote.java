/*
抽象类  abstract
    抽象类的所有方法，继承了他的子类都必须实现他的方法。除非子类也是抽象类。
特点：
     1.不能new抽象类；  他是个约束，只能靠子类去实现；
     2.抽象类里面可以有普通方法，但抽象方法必须在抽象类中；
 */



/*
接口  interface
    1.只有规范；专业的约束；自己无法写方法。
    2.定义一些方法，让不同的人实现；

    3.接口中的所有定义都是抽象的：public abstract；
    4.接口中的属性默认是常量   public static final；

    5.接口不能被实例化，接口中没有构造方法。

    6.类可以实现接口：  implements 多个接口；
    7.实现了接口的类，就需要实现接口中的方法；
    8.利用接口实现多继承；
 */



